export function nextInOrder<T>(order: readonly T[], current: T): T {
  const idx = order.indexOf(current);
  if (idx < 0) return order[0];
  return order[(idx + 1) % order.length];
}

export function formatMoistureStateLabel(state: MoistureState): string {
  switch (state) {
    case "plastic":
      return "Plastic (Wet)";
    case "leather-hard":
      return "Leather-Hard";
    case "bone-dry":
      return "Bone-Dry";
    case "bisqueware":
      return "Bisqueware";
  }
}
